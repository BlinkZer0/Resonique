# ============================================================================
#  Builds web/index.html: ONE self-contained file with the UI (vst/ui), the
#  engine compiled to WebAssembly (webhost/wasm-engine.cpp + Source/dsp, via
#  Emscripten), the web host (webhost/web-host.js) and the factory presets.
#  Also copies it to docs/index.html for GitHub Pages.
#  Usage: powershell -ExecutionPolicy Bypass -File vst\webhost\build-web.ps1 [-SkipWasm]
#  Emscripten: EMSDK in the environment, %LOCALAPPDATA%\ResoniqueVST\emsdk, or a sibling project's
#  (%LOCALAPPDATA%\EightBallVST\emsdk). Install: git clone emsdk, emsdk install latest, emsdk activate latest.
#  -SkipWasm reuses the last .wasm.
# ============================================================================
param([switch]$SkipWasm)
$ErrorActionPreference = 'Stop'
$vst  = Split-Path $PSScriptRoot -Parent
$repo = Split-Path $vst -Parent
$ui   = Join-Path $vst 'ui'
$out  = Join-Path $repo 'web\index.html'
$work = Join-Path $env:LOCALAPPDATA 'ResoniqueVST\wasm'
$wasm = Join-Path $work 'resonique.wasm'
$utf8 = [Text.UTF8Encoding]::new($false)
$read = { param($path) [IO.File]::ReadAllText($path, $utf8) }
$version = (Select-String -Path (Join-Path $vst 'CMakeLists.txt') -Pattern 'project\(ResoniqueVST VERSION ([0-9.]+)').Matches[0].Groups[1].Value

# ---- 1. the engine -> WebAssembly ------------------------------------------------------------
if (-not $SkipWasm -or -not (Test-Path $wasm)) {
    $candidates = @($env:EMSDK, (Join-Path $env:LOCALAPPDATA 'ResoniqueVST\emsdk'), (Join-Path $env:LOCALAPPDATA 'EightBallVST\emsdk')) | Where-Object { $_ }
    $sdk = $candidates | Where-Object { Test-Path (Join-Path $_ 'upstream\emscripten\emcc.py') } | Select-Object -First 1
    if (-not $sdk) { throw "Emscripten not found (tried: $($candidates -join ', ')); see the header of this script" }
    $node = Get-ChildItem (Join-Path $sdk 'node') | Select-Object -First 1
    $env:EMSDK = $sdk
    $env:PATH = "$sdk;$sdk\upstream\emscripten;$($node.FullName)\bin;$env:PATH"
    New-Item -ItemType Directory -Force $work | Out-Null
    $src = Join-Path $PSScriptRoot 'wasm-engine.cpp'
    $kernels = @('Kernels.cpp', 'Kernels_sse.cpp', 'Kernels_avx2.cpp') | ForEach-Object { Join-Path $vst "Source\dsp\$_" }
    $exports = (Select-String -Path $src -Pattern 'RQ_EXPORT \S+ (rq_\w+)' -AllMatches).Matches | ForEach-Object { '_' + $_.Groups[1].Value }
    $exports += '_malloc', '_free'
    Write-Host "[Resonique] em++ ($($exports.Count) exports)..."
    & em++ $src @kernels -O3 -std=c++20 "-I$(Join-Path $vst 'Source')" -fno-exceptions -fno-rtti -msimd128 -ffast-math `
        -s STANDALONE_WASM=1 --no-entry -s INITIAL_MEMORY=67108864 -s ALLOW_MEMORY_GROWTH=1 -s STACK_SIZE=1048576 `
        -s EXPORTED_FUNCTIONS="[$($exports -join ',')]" -o $wasm
    if ($LASTEXITCODE -ne 0) { throw "em++ failed" }
}
$wasmB64 = [Convert]::ToBase64String([IO.File]::ReadAllBytes($wasm))
Write-Host ("[Resonique] wasm {0:N0} KB" -f ((Get-Item $wasm).Length / 1KB))

# ---- 2. the page --------------------------------------------------------------------------------
$html = & $read (Join-Path $ui 'index.html')
function Script([string]$code) {
    if ($code -match '</script') { throw 'inlined code must not contain </script' }
    return "<script>`n$code`n</script>"
}
$css = & $read (Join-Path $ui 'css\style.css')
$html = $html.Replace('<link rel="stylesheet" href="css/style.css">', "<style>`n$css`n</style>")

# the web host, the wasm and the factory presets go in before the bridge (engine-juce.js) is constructed
$presets = (& $read (Join-Path $vst 'presets\factory_presets.json')).Trim()
$hostScripts = @(
    (Script ("// the engine, compiled to WebAssembly from vst/Source (vst/webhost/wasm-engine.cpp)`nconst RESONIQUE_WASM_B64 = '" + $wasmB64 + "';`nconst RESONIQUE_VERSION = '" + $version + "';")),
    (Script ("// the factory presets (vst/presets/factory_presets.json, generated by make_presets.py)`nconst FACTORY_JSON = " + $presets + ';'))
) -join "`n"
$hostJs = Script (& $read (Join-Path $PSScriptRoot 'web-host.js'))
$html = [regex]::Replace($html, '<script src="js/([\w.-]+)"></script>', {
    param($m)
    $name = $m.Groups[1].Value
    $code = Script (& $read (Join-Path $ui "js\$name"))
    if ($name -eq 'params.js') { return "$code`n$hostScripts`n$hostJs" }   # host after params.js (it needs PARAM_DEFS), before engine-juce.js
    return $code
})
$html = $html.Replace('<title>Resonique</title>', "<title>Resonique $version - physically modelled piano</title>`n  <meta name=`"description`" content=`"Resonique: a physically modelled acoustic piano that runs in the browser. The same engine as the VST3 plugin, compiled to WebAssembly.`">")
New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
[IO.File]::WriteAllText($out, $html, $utf8)
$docs = Join-Path $repo 'docs\index.html'
[IO.File]::WriteAllText($docs, $html, $utf8)
Write-Host ("[Resonique] wrote {0} ({1:N0} KB) and docs\index.html" -f $out, ((Get-Item $out).Length / 1KB))
